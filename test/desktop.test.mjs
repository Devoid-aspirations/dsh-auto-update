test('only a real dsh-desktop project is accepted', () => {
  const parent = mkdtempSync(join(tmpdir(), 'dsh-ws-'))
  const good = project({ parent })
  const foreign = project({ parent, name: 'something-else' })
  assert.equal(findDesktopProject(good.dir, '')?.dir, good.dir)
  assert.equal(findDesktopProject(foreign.dir, ''), null, 'a project that is not dsh-desktop is refused')
  assert.equal(findDesktopProject(null, ''), null, 'nothing configured and nothing to look beside means nothing found')
  // The sibling default: <pluginDir>/../dsh-desktop, which is a linked checkout's layout.
  const pluginDir = join(parent, 'dsh-auto-update')
  assert.equal(findDesktopProject(null, pluginDir)?.dir, good.dir)
  // The INSTALLED layout: the plugin lives in a profile's node_modules, and the
  // project sits beside the directory it was installed FROM. This is the case
  // that auto-detection got wrong in the field.
  const installedPluginDir = join(parent, 'profile', 'node_modules', 'dsh-auto-update')
  assert.equal(findDesktopProject(null, installedPluginDir), null, 'the installed copy has no sibling project')
  assert.equal(findDesktopProject(null, installedPluginDir, pluginDir)?.dir, good.dir, 'the install source supplies it')
  assert.equal(desktopCandidates(null, pluginDir, pluginDir).length, 1, 'candidates are deduplicated')
  clean(parent)
})

test('the version rewrite touches one line and keeps a backup', () => {
  const { dir, parent } = project({ version: '1.0.0' })
  const file = join(dir, 'package.json')
  const before = readFileSync(file, 'utf8')

  const written = writeManifestVersion(file, '0.2.0-rc.2')
  assert.equal(written.changed, true)
  assert.equal(written.previous, '1.0.0')
  assert.equal(existsSync(written.backup), true, 'the previous manifest is kept')
  const after = readFileSync(file, 'utf8')
  assert.equal(after.replace('0.2.0-rc.2', '1.0.0'), before, 'every other byte is untouched')
  assert.equal(JSON.parse(after).version, '0.2.0-rc.2')
  assert.equal(JSON.parse(after).name, 'dsh-desktop', 'the rest of the manifest survives')

  const again = writeManifestVersion(file, '0.2.0-rc.2')
  assert.equal(again.changed, false, 'a second sync is a no-op')
  clean(parent)
})

