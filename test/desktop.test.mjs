test('the plan distinguishes up to date, version-only and repackage', () => {
  const current = project({ version: '0.2.0-rc.2', packaged: '0.2.0-rc.2', zip: true })
  const stalePackage = project({ version: '0.2.0-rc.2', packaged: '1.0.0', zip: true })
  const manifest = { manifest: { version: '0.2.0-rc.2' } }

  const fresh = planDesktopSync({ project: { ...findDesktopProject(current.dir, ''), ...manifest }, mode: 'package', harnessVersion: '0.2.0-rc.2', zipPath: current.zipPath })
  assert.equal(fresh.action, 'up-to-date', fresh.reason)
  assert.deepEqual(fresh.drift, [], 'a payload that matches the project is not drift')
  assert.equal(fresh.payload, 'DSH Desktop Test', 'the plan names the payload it judged')

  const missingZip = planDesktopSync({ project: { ...findDesktopProject(current.dir, ''), ...manifest }, mode: 'package', harnessVersion: '0.2.0-rc.2', zipPath: join(current.dir, 'dist', 'nope.zip') })
  assert.equal(missingZip.action, 'package', 'a missing distributable is a reason to rebuild')
  assert.match(missingZip.reason, /zip is missing/u)

  const stale = planDesktopSync({ project: { ...findDesktopProject(stalePackage.dir, ''), ...manifest }, mode: 'package', harnessVersion: '0.2.0-rc.2', zipPath: stalePackage.zipPath })
  assert.equal(stale.action, 'package')
  assert.match(stale.reason, /packaged build says 1\.0\.0/u)

  const versionOnly = planDesktopSync({ project: { ...findDesktopProject(stalePackage.dir, ''), ...manifest }, mode: 'version', harnessVersion: '0.2.0-rc.2', zipPath: stalePackage.zipPath })
  assert.equal(versionOnly.action, 'up-to-date', 'version mode does not care about the build')
  clean(current.parent)
  clean(stalePackage.parent)
})

test('a distributable that is not a complete archive is a reason to rebuild', () => {
  // A refresh that died halfway leaves bytes that `existsSync` would call a
  // distributable for ever.
  const truncated = project({ version: '0.2.0-rc.2', packaged: '0.2.0-rc.2', zipBytes: Buffer.from('zipbytes') })
  const manifest = { manifest: { version: '0.2.0-rc.2' } }
  assert.equal(inspectZip(truncated.zipPath).valid, false, 'a truncated zip is not complete')
  assert.equal(inspectZip(truncated.zipPath).bytes, 8)
  assert.deepEqual(inspectZip(join(truncated.dir, 'nope.zip')), { valid: false, bytes: null, at: null }, 'a missing file is answered, not thrown')
  const plan = planDesktopSync({ project: { ...findDesktopProject(truncated.dir, ''), ...manifest }, mode: 'package', harnessVersion: '0.2.0-rc.2', zipPath: truncated.zipPath })
  assert.equal(plan.action, 'package')
  assert.match(plan.reason, /zip is incomplete/u)

  const whole = project({ version: '0.2.0-rc.2', packaged: '0.2.0-rc.2', zip: true })
  assert.equal(inspectZip(whole.zipPath).valid, true, 'a complete archive is accepted')
  clean(truncated.parent)
  clean(whole.parent)
})

test('a distributable older than the payload it should hold is a reason to rebuild', () => {
  // The ordering IS the guarantee: build → verify → archive. An archive that
  // predates the payload holds the PREVIOUS build, however complete it looks —
  // which is what a build that died before the zip step leaves behind.
  const { dir, parent, zipPath } = project({ version: '0.2.0-rc.2', packaged: '0.2.0-rc.2', zip: true })
  const found = findDesktopProject(dir, '')
  const fresh = planDesktopSync({ project: found, mode: 'package', harnessVersion: '0.2.0-rc.2', zipPath })
  assert.equal(fresh.action, 'up-to-date', fresh.reason)

  const old = new Date(Date.now() - 86_400_000)
  utimesSync(zipPath, old, old)
  const lagging = planDesktopSync({ project: found, mode: 'package', harnessVersion: '0.2.0-rc.2', zipPath })
  assert.equal(lagging.action, 'package')
  assert.match(lagging.reason, /predates the packaged build/u)
  assert.equal(lagging.stalePackage, true)
  clean(parent)
})

