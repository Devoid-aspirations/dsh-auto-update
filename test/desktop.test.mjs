test('the newest payload answers, and zipSource pins one', () => {
  const { dir, parent } = project({ version: '0.2.0-rc.2' })
  const old = addPayload(dir, { folder: 'win-unpacked', layout: 'asar', version: '0.1.0', at: 1_000_000 })
  addPayload(dir, { folder: 'DSH Desktop Test', layout: 'unpacked', version: '0.2.0-rc.2' })
  const found = listPayloads(dir, null)
  assert.deepEqual(found.payloads.map((item) => item.folder), ['DSH Desktop Test', 'win-unpacked'], 'newest first')
  assert.equal(choosePayload(found.payloads, null)?.layout, 'unpacked')
  assert.equal(choosePayload(found.payloads, 'win-unpacked')?.file, old.file, 'the pin chooses the older layout')
  assert.equal(readPackagedVersion(dir, { zipSource: 'win-unpacked' }).version, '0.1.0')
  assert.equal(readPackagedVersion(dir, {}).version, '0.2.0-rc.2', 'without a pin the build that just ran answers')
  clean(parent)
})

