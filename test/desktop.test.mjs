/**
 * Desktop wrapper sync.
 *
 * The fixtures are the REAL shapes, because the bug this file now guards was a
 * shape mistake: `electron-builder --win dir` writes
 * `dist/win-unpacked/resources/app.asar`, NOT
 * `dist/<productName>/resources/app/package.json`, so the artifact check could
 * not see a default build at all. Both layouts are built here — the unpacked
 * folder and the packed archive — and the build step itself is a STUB with a
 * real process boundary: the point is the transaction around the build
 * (plan → manifest → build → verify the artifact → zip → record), not
 * electron-builder.
 */

