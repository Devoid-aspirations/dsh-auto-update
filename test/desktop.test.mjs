/** The asar writer, as a URL a generated stub script can import. */
const ASAR_URL = new URL('./support/asar.mjs', import.meta.url).href

/** A zip that is complete but holds nothing: 22 bytes of end-of-central-directory. */
const EMPTY_ZIP = Buffer.concat([Buffer.from([0x50, 0x4b, 0x05, 0x06]), Buffer.alloc(18)])

/**
 * Write the payload one electron-builder layout would produce.
 *
 * `package.json` is GENERATED by the packager (its version is the build's), so it
 * is written from `version` alone; every other shipped file is a copy of the
 * project's — unless `shell` overrides it, which is how a stale build is staged.
 * @param {string} projectDir - the project the payload is built from.
 * @param {{folder: string, layout?: string, version: string, productName?: string, shipped?: string[], shell?: string | null, output?: string, at?: number | null, broken?: boolean}} shape - what to write.
 * @returns {{folder: string, layout: string, root: string, file: string}} the payload.
 */
function addPayload(projectDir, shape) {
  const { folder, version, productName = 'DSH Desktop Test', shipped = ['main.js'], shell = null, output = 'dist', at = null, broken = false } = shape
  const layout = shape.layout ?? 'unpacked'
  const root = join(projectDir, output, folder)
  const resources = join(root, 'resources')
  if (broken) {
    // An archive that is there but does not parse: the payload folder is named as
    // the packager names it, and there is no unpacked directory beside it.
    mkdirSync(resources, { recursive: true })
    const file = join(resources, 'app.asar')
    writeFileSync(file, 'this is not an archive', 'utf8')
    if (at !== null) utimesSync(file, new Date(at), new Date(at))
    return { folder, layout: 'asar', root, file }
  }
  const appDir = join(resources, 'app')
  mkdirSync(appDir, { recursive: true })
  const manifest = `${JSON.stringify({ name: 'dsh-desktop', productName, version }, null, 2)}\n`
  const contents = shipped.map((file) => ({
    path: file,
    content: file === 'main.js' && shell !== null ? shell : readFileSync(join(projectDir, file), 'utf8'),
  }))
  if (layout === 'asar') {
    const file = join(root, 'resources', 'app.asar')
    writeAsar(file, [{ path: 'package.json', content: manifest }, ...contents])
    rmSync(appDir, { recursive: true, force: true })
    if (at !== null) utimesSync(file, new Date(at), new Date(at))
    return { folder, layout, root, file }
  }
  const file = join(appDir, 'package.json')
  writeFileSync(file, manifest, 'utf8')
  for (const entry of contents) writeFileSync(join(appDir, entry.path), entry.content, 'utf8')
  if (at !== null) utimesSync(file, new Date(at), new Date(at))
  return { folder, layout, root, file }
}

/**
 * Build a fake dsh-desktop project.
 *
 * The layout mirrors the real one: the project is a directory NAMED
 * `dsh-desktop` inside a parent, and the plugin lives beside it in the same
 * parent — which is exactly what the sibling auto-detection looks for. The
 * product name carries a `Test` suffix so a build never collides with a running
 * "DSH Desktop" on the machine running the suite.
 * @param {{parent?: string, version?: string, packaged?: string | null, layout?: string, shipped?: string[], files?: string[], shell?: string | null, packagedShell?: string | null, output?: string, folder?: string, zip?: boolean, zipName?: string, zipBytes?: Buffer, name?: string, productName?: string, preload?: boolean}} [shape] - what to create.
 * @returns {{dir: string, parent: string, outputRoot: string, zipPath: string}} the project paths.
 */
function project(shape = {}) {
  const parent = shape.parent ?? mkdtempSync(join(tmpdir(), 'dsh-project-'))
  const name = shape.name ?? 'dsh-desktop'
  const productName = shape.productName ?? 'DSH Desktop Test'
  const version = shape.version ?? '1.0.0'
  const output = shape.output ?? 'dist'
  const files = shape.files ?? ['main.js']
  const root = join(parent, name)
  mkdirSync(root, { recursive: true })
  const manifest = {
    name,
    productName,
    version,
    description: '版本与 dsh 核心同步',
    main: 'main.js',
    scripts: { 'dist:dir': 'electron-builder --win dir' },
    build: { files, ...(shape.output === undefined ? {} : { directories: { output: shape.output } }) },
  }
  writeFileSync(join(root, 'package.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8')
  writeFileSync(join(root, 'main.js'), shape.shell ?? '// shell\n', 'utf8')
  if (files.includes('preload.js')) writeFileSync(join(root, 'preload.js'), '// preload\n', 'utf8')
  const outputRoot = join(root, output)
  if (shape.packaged !== undefined && shape.packaged !== null) {
    addPayload(root, {
      folder: shape.folder ?? (shape.layout === 'asar' || shape.layout === 'broken' ? 'win-unpacked' : productName),
      layout: shape.layout ?? 'unpacked',
      version: shape.packaged,
      productName,
      shipped: shape.shipped ?? files,
      shell: shape.packagedShell ?? null,
      output,
      broken: shape.layout === 'broken',
    })
  }
  const zipPath = join(outputRoot, shape.zipName ?? 'DSH-Desktop-绿色版.zip')
  if (shape.zip === true) {
    mkdirSync(outputRoot, { recursive: true })
    writeFileSync(zipPath, EMPTY_ZIP)
  }
  if (shape.zipBytes !== undefined) {
    mkdirSync(outputRoot, { recursive: true })
    writeFileSync(zipPath, shape.zipBytes)
  }
  return { dir: root, parent, outputRoot, zipPath }
}

/**
 * A build stub: a real child process that writes the payload the real build
 * would, honouring the same environment switches.
 * @param {string} projectDir - the project the build runs in.
 * @returns {string[]} the argv to run it.
 */
function buildStub(projectDir) {
  const script = join(projectDir, 'stub-build.mjs')
  writeFileSync(
    script,
    `import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { writeAsar } from ${JSON.stringify(ASAR_URL)}
// fileURLToPath, not new URL(...).pathname. On Windows pathname is '/D:/...'
// (leading slash must go), on Linux it is '/home/runner/...' (leading slash is
// the root and must stay). Stripping a slash unconditionally turned the Linux
// path into the relative 'home/runner/...', so the stub could not find its own
// package.json and every package-mode test failed there with exit code 1.
const root = dirname(fileURLToPath(import.meta.url))
const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
if (process.env.STUB_BUILD_FAIL === '1') { process.exit(3) }
if (process.env.STUB_BUILD_SLEEP !== undefined) { await new Promise((resolve) => setTimeout(resolve, Number(process.env.STUB_BUILD_SLEEP))) }
const version = process.env.STUB_BUILD_SHIP_OLD === '1' ? '1.0.0' : manifest.version
const shipped = [{ path: 'package.json', content: JSON.stringify({ name: manifest.name, productName: manifest.productName, version }, null, 2) }]
for (const entry of manifest.build.files) {
  if (typeof entry === 'string' && !entry.includes('*')) shipped.push({ path: entry, content: process.env.STUB_BUILD_OLD_SHELL === '1' && entry === 'main.js' ? '// stale shell\\n' : readFileSync(join(root, entry), 'utf8') })
}
if (process.env.STUB_BUILD_ASAR === '1') {
  const resources = join(root, 'dist', 'win-unpacked', 'resources')
  mkdirSync(resources, { recursive: true })
  writeAsar(join(resources, 'app.asar'), shipped)
} else {
  const appDir = join(root, 'dist', manifest.productName, 'resources', 'app')
  mkdirSync(appDir, { recursive: true })
  for (const file of shipped) writeFileSync(join(appDir, file.path), file.content)
}
process.stdout.write('stub build wrote ' + version + '\\n')
`,
    'utf8',
  )
  return [process.execPath, script]
}

